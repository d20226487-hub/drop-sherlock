def normalize_tld(entry: str) -> str:
    """Lowercase and strip `*.` / `*` / leading-dot prefixes so pasted
    lists in any of the common shapes normalize to a bare suffix."""
    p = (entry or "").strip().lower()
    if p.startswith("*."):
        p = p[2:]
    elif p.startswith("*"):
        p = p[1:]
    if p.startswith("."):
        p = p[1:]
    return p


def make_tld_matcher(tlds: list[str]):
    """Return `match(domain) -> bool` for suffix semantics, fast enough to
    stream a global export through: single-label TLDs match on the
    domain's last label via a set lookup; multi-label entries (co.uk
    style ??? a handful) fall back to endswith checks."""
    singles: set[str] = set()
    multi: list[str] = []
    for t in tlds:
        n = normalize_tld(t)
        if not n:
            continue
        if "." in n:
            multi.append("." + n)
        else:
            singles.add(n)

    def match(domain: str) -> bool:
        d = (domain or "").lower()
        if not d:
            return False
        last = d.rsplit(".", 1)[-1]
        if last in singles:
            return True
        return any(d.endswith(m) for m in multi)

    return match
